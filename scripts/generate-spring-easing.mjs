//
// Generate the CSS spring easing tokens from the single source of truth,
// src/design/motion.ts. The generated block is committed in tokens.css so the
// app never writes easing values at runtime.
//
// Usage:
//   node scripts/generate-spring-easing.mjs           print the block
//   node scripts/generate-spring-easing.mjs --write   update tokens.css
//   node scripts/generate-spring-easing.mjs --check   fail when CSS drifted
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

export const START_MARKER = "/* spring-easing:start (generated by scripts/generate-spring-easing.mjs; do not edit by hand) */";
export const END_MARKER = "/* spring-easing:end */";

// The spring solver intentionally mirrors advanceSpring() in
// src/visual/glass/jelly.ts: semi-implicit Euler with fixed substeps.
const SOLVER_STEP_SECONDS = 1 / 2000;
const SETTLE_DISTANCE = 0.01;
const SETTLE_SPEED = 0.1;
const OVERSHOOT_EPSILON = 0.001;
const OVERSHOOT_LIMIT = 0.02;
const MAX_DURATION_MS = 300;
const SAMPLE_COUNT = 32;
const SAMPLE_SUBSTEPS = 8;

// CSS custom properties are sampled from these motion.ts springs. Fallbacks
// are hand-tuned cubic-beziers for WebView2 builds without linear() support.
export const SPRING_TOKEN_SOURCES = [
  { token: "enter", path: ["identity"], fallback: "cubic-bezier(0.22, 1, 0.36, 1)" },
  { token: "section", path: ["section"], fallback: "cubic-bezier(0.22, 1, 0.36, 1)" },
  { token: "press", path: ["lens", "press"], fallback: "cubic-bezier(0.34, 1.08, 0.64, 1)" },
];

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const MOTION_PATH = resolve(ROOT, "src/design/motion.ts");
const TOKENS_PATH = resolve(ROOT, "src/design/tokens.css");

function unwrapExpression(node) {
  let current = node;
  while (current && (ts.isAsExpression(current) || ts.isSatisfiesExpression(current) || ts.isParenthesizedExpression(current))) {
    current = current.expression;
  }
  return current;
}

function property(object, name) {
  for (const item of object.properties) {
    if (ts.isPropertyAssignment(item) && (ts.isIdentifier(item.name) || ts.isStringLiteral(item.name))
      && item.name.text === name) return unwrapExpression(item.initializer);
  }
  return null;
}

function numberProperty(object, name, label) {
  const value = property(object, name);
  if (!value || !ts.isNumericLiteral(value)) throw new Error(`${label}.${name} must be a numeric literal in motion.ts`);
  return Number(value.text);
}

function springAt(motion, path) {
  let current = motion;
  for (const key of path) {
    if (!ts.isObjectLiteralExpression(current)) throw new Error(`MOTION.${path.join(".")} must be an object literal in motion.ts`);
    current = property(current, key);
    if (!current) throw new Error(`MOTION.${path.join(".")} is missing from motion.ts`);
  }
  if (!ts.isObjectLiteralExpression(current)) throw new Error(`MOTION.${path.join(".")} must be an object literal in motion.ts`);
  const label = `MOTION.${path.join(".")}`;
  const stiffness = numberProperty(current, "stiffness", label);
  const damping = numberProperty(current, "damping", label);
  if (!(stiffness > 0) || !(damping > 0)) throw new Error(`${label} needs positive stiffness and damping values`);
  return { stiffness, damping };
}

/** Read the spring tunings straight out of motion.ts without executing it. */
export function readMotionSprings(sourceText, filename = "motion.ts") {
  const source = ts.createSourceFile(filename, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  let motion = null;
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name) && declaration.name.text === "MOTION") {
        const initializer = unwrapExpression(declaration.initializer);
        if (initializer && ts.isObjectLiteralExpression(initializer)) motion = initializer;
      }
    }
  }
  if (!motion) throw new Error("motion.ts must declare MOTION as an object literal");
  return {
    identity: springAt(motion, ["identity"]),
    section: springAt(motion, ["section"]),
    press: springAt(motion, ["lens", "press"]),
  };
}

function springAtPath(springs, path) {
  if (path.length === 1) return springs[path[0]];
  if (path[0] === "lens" && path[1] === "press") return springs.press;
  throw new Error(`Unsupported spring path: ${path.join(".")}`);
}

function measure(stiffness, damping) {
  let position = 0;
  let velocity = 0;
  let time = 0;
  let peak = 0;
  let peakTime = 0;
  let settle = null;
  while (time < 1.5) {
    const pull = (1 - position) * stiffness;
    velocity += (pull - velocity * damping) * SOLVER_STEP_SECONDS;
    position += velocity * SOLVER_STEP_SECONDS;
    time += SOLVER_STEP_SECONDS;
    if (position > peak) {
      peak = position;
      peakTime = time;
    }
    // When the spring visibly overshoots, it is not settled at the peak; wait
    // for the return toward the goal before accepting the tolerance band.
    const afterPeak = peak - 1 <= OVERSHOOT_EPSILON || time > peakTime + 0.005;
    if (settle === null && afterPeak && Math.abs(1 - position) <= SETTLE_DISTANCE && Math.abs(velocity) <= SETTLE_SPEED) {
      settle = time;
    }
  }
  return { peak, settle: settle ?? 1.5 };
}

// Raise damping only as far as needed to satisfy the <= 2% overshoot contract.
function limitOvershoot(stiffness, damping) {
  const logLimit = Math.log(1 / OVERSHOOT_LIMIT);
  const criticalRatio = Math.sqrt((logLimit * logLimit) / (Math.PI * Math.PI + logLimit * logLimit));
  let effective = Math.max(damping, Math.ceil(2 * criticalRatio * Math.sqrt(stiffness) * 2) / 2);
  let measured = measure(stiffness, effective);
  let guard = 0;
  while (measured.peak > 1 + OVERSHOOT_LIMIT && guard < 200) {
    effective = Math.round((effective + 0.1) * 10) / 10;
    measured = measure(stiffness, effective);
    guard += 1;
  }
  if (measured.peak > 1 + OVERSHOOT_LIMIT) throw new Error(`Cannot limit spring overshoot for stiffness ${stiffness}`);
  return { damping: effective, ...measured };
}

function formatNumber(value) {
  if (Math.abs(value) < 0.00005) return "0";
  return value.toFixed(4).replace(/0+$/, "").replace(/\.$/, "");
}

function sampleSpring(stiffness, damping, horizonSeconds) {
  const steps = (SAMPLE_COUNT - 1) * SAMPLE_SUBSTEPS;
  const h = horizonSeconds / steps;
  let position = 0;
  let velocity = 0;
  const values = [0];
  for (let step = 1; step <= steps; step += 1) {
    const pull = (1 - position) * stiffness;
    velocity += (pull - velocity * damping) * h;
    position += velocity * h;
    if (step % SAMPLE_SUBSTEPS === 0) values.push(position);
  }
  // A spring only approaches its goal asymptotically. Once it is visually
  // settled, advanceSpring() snaps to goal; mirror that for the final stop.
  values[values.length - 1] = 1;
  return values.map(value => Math.min(1 + OVERSHOOT_LIMIT, Math.max(0, value)));
}

export function computeSpringToken(spring) {
  const limited = limitOvershoot(spring.stiffness, spring.damping);
  const durationMs = Math.min(MAX_DURATION_MS, Math.ceil(limited.settle * 100) * 10);
  const values = sampleSpring(spring.stiffness, limited.damping, durationMs / 1000);
  return {
    stiffness: spring.stiffness,
    sourceDamping: spring.damping,
    damping: limited.damping,
    durationMs,
    peak: Math.max(limited.peak, ...values),
    values,
  };
}

export function buildSpringTokenBlock(springs) {
  const curves = SPRING_TOKEN_SOURCES.map(source => {
    const tuning = springAtPath(springs, source.path);
    return { ...source, ...computeSpringToken(tuning) };
  });
  const lines = [];
  lines.push(START_MARKER);
  lines.push("/* Full tier: sampled from MOTION in motion.ts by the same integrator as advanceSpring. */");
  lines.push("/* The cubic-bezier fallback stays active unless the browser supports linear() easing. */");
  lines.push(":root {");
  for (const curve of curves) {
    const capped = curve.damping !== curve.sourceDamping
      ? `, damping raised from ${curve.sourceDamping} to ${curve.damping} for the 2% overshoot limit`
      : "";
    lines.push(`  /* MOTION.${curve.path.join(".")} ${curve.stiffness}/${curve.sourceDamping}${capped}; `
      + `${curve.durationMs}ms, peak ${((curve.peak - 1) * 100).toFixed(2)}%. */`);
    lines.push(`  --duration-spring-${curve.token}: ${curve.durationMs}ms;`);
    lines.push(`  --ease-spring-${curve.token}: ${curve.fallback};`);
  }
  lines.push("}");
  lines.push("@supports (transition-timing-function: linear(0, 1)) {");
  lines.push("  :root {");
  for (const curve of curves) {
    lines.push(`    --ease-spring-${curve.token}: linear(${curve.values.map(formatNumber).join(", ")});`);
  }
  lines.push("  }");
  lines.push("}");
  lines.push("/* Lite and reduced-transparency (fade) keep the flat ease-out curve. */");
  lines.push('[data-effects="lite"],');
  lines.push('[data-reduced-transparency="true"] {');
  for (const curve of curves) lines.push(`  --ease-spring-${curve.token}: var(--ease-out);`);
  lines.push("}");
  lines.push("/* Static, high-contrast and reduced-motion collapse every spring transition to zero. */");
  lines.push('[data-reduced-motion="true"],');
  lines.push('[data-high-contrast="true"],');
  lines.push('[data-motion-tier="none"] {');
  for (const curve of curves) {
    lines.push(`  --ease-spring-${curve.token}: var(--ease-out);`);
    lines.push(`  --duration-spring-${curve.token}: 0s;`);
  }
  lines.push("}");
  lines.push("@media (prefers-reduced-motion: reduce) {");
  lines.push("  :root {");
  for (const curve of curves) {
    lines.push(`    --ease-spring-${curve.token}: var(--ease-out);`);
    lines.push(`    --duration-spring-${curve.token}: 0s;`);
  }
  lines.push("  }");
  lines.push("}");
  lines.push("@media (prefers-reduced-transparency: reduce) {");
  lines.push("  :root {");
  for (const curve of curves) lines.push(`    --ease-spring-${curve.token}: var(--ease-out);`);
  lines.push("  }");
  lines.push("}");
  lines.push(END_MARKER);
  return lines.join("\n");
}

export function extractSpringTokenBlock(css) {
  const start = css.indexOf(START_MARKER);
  if (start < 0) throw new Error(`tokens.css is missing ${START_MARKER}`);
  const end = css.indexOf(END_MARKER, start);
  if (end < 0) throw new Error(`tokens.css is missing ${END_MARKER}`);
  return css.slice(start, end + END_MARKER.length);
}

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, "\n");
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const length = Math.max(expectedLines.length, actualLines.length);
  for (let index = 0; index < length; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      const at = index + 1;
      return `first difference at generated line ${at}\n  expected: ${expectedLines[index] ?? "<end of block>"}\n  actual:   ${actualLines[index] ?? "<end of block>"}`;
    }
  }
  return "generated block differs only by line endings";
}

export function checkSpringTokens(css, springs) {
  const expected = buildSpringTokenBlock(springs);
  let actual;
  try {
    actual = extractSpringTokenBlock(css);
  } catch (error) {
    return [error.message];
  }
  if (normalizeNewlines(actual) === normalizeNewlines(expected)) return [];
  return [
    "Spring easing tokens in src/design/tokens.css are out of date with src/design/motion.ts.",
    "Run `node scripts/generate-spring-easing.mjs --write` and commit the result.",
    firstDifference(expected, normalizeNewlines(actual)),
  ];
}

export function replaceSpringTokenBlock(css, block) {
  const start = css.indexOf(START_MARKER);
  const end = css.indexOf(END_MARKER, start);
  if (start < 0 || end < 0) throw new Error("tokens.css is missing the spring-easing:start/end markers");
  const newline = css.includes("\r\n") ? "\r\n" : "\n";
  const rendered = block.replace(/\n/g, newline);
  return css.slice(0, start) + rendered + css.slice(end + END_MARKER.length);
}

function main() {
  const write = process.argv.includes("--write");
  const check = process.argv.includes("--check");
  if (write && check) throw new Error("Use either --write or --check, not both");
  const springs = readMotionSprings(readFileSync(MOTION_PATH, "utf8"), MOTION_PATH);
  if (write) {
    const css = readFileSync(TOKENS_PATH, "utf8");
    const next = replaceSpringTokenBlock(css, buildSpringTokenBlock(springs));
    writeFileSync(TOKENS_PATH, next);
    console.log("Spring easing tokens regenerated in src/design/tokens.css.");
    return;
  }
  if (check) {
    const errors = checkSpringTokens(readFileSync(TOKENS_PATH, "utf8"), springs);
    if (errors.length) {
      console.error(errors.join("\n"));
      process.exitCode = 1;
      return;
    }
    console.log("Spring easing tokens match src/design/motion.ts.");
    return;
  }
  console.log(buildSpringTokenBlock(springs));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
